"""
Python script to put together the metrics_df of the different runs
generated by a quantile_reg experiment
"""

# general imports
import os
import sys
import ipdb
import numpy as np
import pandas as pd
from scipy import stats
from statsmodels.stats.power import TTestIndPower

src_path = os.path.join(os.path.dirname(__file__),"..","..","src",
)
sys.path.append(src_path)

from utils import (
    generate_path,
    load_yaml_to_dict,
    ExperimentConfig,
    get_most_recent_file,
    get_most_recent_dir,
    open_element,
    save_element,
)

from perf import(
    lifes_metrics,
    sub_lifes_metrics,
    df_with_index_to_obsidian_table
)

experiment_path = os.path.join(os.path.dirname(os.path.dirname(os.path.realpath(__file__))),"chronos_exp")

config_path=os.path.join(experiment_path,"config","ssm_exp_config.yaml")
config=load_yaml_to_dict(config_path)
config=ExperimentConfig(config)

# Get the outputs directory of the most recent experiment
outputs_dict_path = generate_path(basepath=experiment_path,
                                folders=[
                                    "outputs",
                                    config.model_name,
                                    config.cmapss_models,
                                    config.approach,
                                    "quantile_reg",
                                    config.exp_name
                                ])
# outputs_dict_path = get_most_recent_dir(outputs_path,file_pos=config.file_pos)

metrics_dfs = []

for i in range(config.n_runs):

    metrics_df = pd.DataFrame()
    run_quantile_path = generate_path(basepath=outputs_dict_path,
                                      folders=[f"run_{i+1}"])

    for quantile in config.quantiles:
        quantile_path = generate_path(basepath=run_quantile_path,
                                      folders=[f"quantile_{quantile}"])
        quantile_df = lifes_metrics(
            config=config,
            outputs_path=quantile_path,
            compute_stats=False
        )
        metrics_df[f"quantile_{quantile}"] = quantile_df["Eval Loss"]

    metrics_dfs.append(metrics_df)

# Create a new pd.DataFrame with the same shape of all the metrics_df which contains the mean of all the pd.DataFrames inside metrics_dfs
mean_metrics_df=(sum(metrics_dfs)/len(metrics_dfs)).round(2)
# Compute the mean, median and std of the metrics
mean_metrics_df.loc["Life_mean"] = mean_metrics_df.mean(axis=0).round(2)
mean_metrics_df.loc["Life_median"] = mean_metrics_df.median(axis=0).round(2)
mean_metrics_df.loc["Life_std"] = mean_metrics_df.std(axis=0).round(2)

if config.stat_test:
    metrics_df_run=[]
    runs=[]
    for i,metrics_df in enumerate(metrics_dfs):
        metrics_df_run.append(metrics_df.mean(axis=0))
        runs.append(f"run_{i+1}")

    metrics_df_runs=pd.concat(metrics_df_run,axis=1)
    metrics_df_runs.columns=runs
    q1=metrics_df_runs.loc[f"quantile_{config.quantile_to_test[0]}"]
    q2=metrics_df_runs.loc[f"quantile_{config.quantile_to_test[1]}"]
    t_stat,p_val=stats.ttest_ind(q1,q2)
    print('#'* 50)
    print(f"Independent T-test results between quantiles {config.quantile_to_test[0]} and {config.quantile_to_test[1]}")
    print(f"t-statistic: {t_stat:.4f}")
    print(f"p-value: {p_val:.4f}")
    print('#'* 50)

    if config.power_analysis:
        effect_size=abs(q1.mean()-q2.mean())/np.std(np.concatenate([q1,q2]))
        analysis=TTestIndPower()
        sample_size=analysis.solve_power(
                                         effect_size=effect_size,
                                         alpha=0.05,
                                         power=0.8,
                                         alternative='two-sided'
                                         )
        print('#'* 50)
        print(f"Power analysis between quantiles {config.quantile_to_test[0]} and {config.quantile_to_test[1]}")
        print(f"Suggested sample size: {sample_size}")
        print('#'* 50)

print('#'* 50)
print(f"Mean eval loss over all the test lifes:\n{mean_metrics_df.loc['Life_mean']}")
print('#'* 50)
print(f"Median eval loss over all the test lifes:\n{mean_metrics_df.loc['Life_median']}")
print('#'* 50)
print(f"Std eval loss over all the test lifes:\n{mean_metrics_df.loc['Life_std']}")
print('#'* 50)

if config.save_mean_metrics_df:
    metrics_df_path = generate_path(basepath=experiment_path,
                                    folders=[
                                        "metrics",
                                        config.model_name,
                                        config.cmapss_models,
                                        config.approach,
                                        "quantile_reg",
                                        config.exp_name
                                    ])
    filename=f"{config.model_name}_{config.cmapss_models}_{config.approach}_quantile_reg_global_metrics_df"
    save_element(
        mean_metrics_df,
        dirpath=metrics_df_path,
        filename=filename,
        filetype="pickle",
    )

if config.obsidian_table:
    if config.sub_lifes_metrics:
        sub_metrics_df = sub_lifes_metrics(
            config=config,
            metrics_df=mean_metrics_df,
            compute_stats=True
        )
        obsidian_table = df_with_index_to_obsidian_table(sub_metrics_df)
    else:
        obsidian_table = df_with_index_to_obsidian_table(mean_metrics_df)
    print('#'* 50)
    print(obsidian_table)
    print('#'* 50)
